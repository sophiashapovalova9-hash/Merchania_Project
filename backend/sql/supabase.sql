-- Сами картинки этот скрипт не кладёт: их допишет бэкенд в imagedata при первом запуске.
insert into productmedia (productid, imageurl, ismain, mimetype)
select p.productid,
       '/api/products/' || p.productid::text || '/image',
       true,
       'image/png'
from product p
where not exists (
    select 1 from productmedia m where m.productid = p.productid
);

insert into cart (userid, productid, quantity)
select u.userid, p.productid, 1
from useraccount u
join product p on p.title in ('Акриловый стенд "Странник"', 'Значок "Паймон"')
where u.email = 'ivan@example.com'
on conflict (userid, productid) do nothing;

select setval(pg_get_serial_sequence('role', 'roleid'), (select coalesce(max(roleid), 1) from role));
select setval(pg_get_serial_sequence('useraccount', 'userid'), (select coalesce(max(userid), 1) from useraccount));
select setval(pg_get_serial_sequence('artistdetail', 'artistid'), (select coalesce(max(artistid), 1) from artistdetail));
select setval(pg_get_serial_sequence('fandom', 'fandomid'), (select coalesce(max(fandomid), 1) from fandom));
select setval(pg_get_serial_sequence('category', 'categoryid'), (select coalesce(max(categoryid), 1) from category));
select setval(pg_get_serial_sequence('product', 'productid'), (select coalesce(max(productid), 1) from product));
select setval(pg_get_serial_sequence('orderstatus', 'statusid'), (select coalesce(max(statusid), 1) from orderstatus));

