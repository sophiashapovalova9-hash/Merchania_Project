-- Как запустить: Supabase → SQL Editor → New query → вставь ВЕСЬ этот файл → Run.
-- Один раз, на пустом проекте. Пароль сюда не пишется: он живёт только в backend/.env.
-- Имена таблиц без кавычек: Postgres сам делает их строчными (Product → product).
-- Запросы бэкенда написаны так же, как раньше, поэтому имена совпадут.
-- RLS не включай: бэкенд ходит паролем базы, не ключом anon.

begin;

create table if not exists role (
    roleid int generated by default as identity primary key,
    rolename text not null unique
);

create table if not exists useraccount (
    userid int generated by default as identity primary key,
    email text not null unique,
    passwordhash text not null,
    roleid int not null references role (roleid),
    createdat timestamptz not null default now()
);

create table if not exists userprofile (
    profileid int generated by default as identity primary key,
    userid int not null unique references useraccount (userid),
    firstname text not null,
    lastname text not null,
    patronymic text null,
    phone text null
);

create table if not exists artistdetail (
    artistid int generated by default as identity primary key,
    userid int not null unique references useraccount (userid),
    shopname text not null,
    bio text null,
    rating numeric(3, 2) not null default 0
);

create table if not exists fandom (
    fandomid int generated by default as identity primary key,
    fandomname text not null unique,
    description text null
);

create table if not exists category (
    categoryid int generated by default as identity primary key,
    categoryname text not null unique
);

create table if not exists product (
    productid int generated by default as identity primary key,
    artistid int not null references artistdetail (artistid),
    categoryid int not null references category (categoryid),
    fandomid int not null references fandom (fandomid),
    title text not null,
    description text null,
    price numeric(12, 2) not null,
    stockquantity int not null default 0,
    createdat timestamptz not null default now()
);

create table if not exists tag (
    tagid int generated by default as identity primary key,
    tagname text not null unique
);

create table if not exists producttag (
    productid int not null references product (productid),
    tagid int not null references tag (tagid),
    primary key (productid, tagid)
);

create table if not exists productmedia (
    mediaid int generated by default as identity primary key,
    productid int not null references product (productid),
    imageurl text not null,
    ismain boolean not null default false,
    imagedata bytea null,
    mimetype text null
);

create table if not exists orderstatus (
    statusid int generated by default as identity primary key,
    statusname text not null unique
);

create table if not exists orders (
    orderid int generated by default as identity primary key,
    buyerid int not null references useraccount (userid),
    statusid int not null references orderstatus (statusid),
    orderdate timestamptz not null default now(),
    totalamount numeric(12, 2) not null,
    shippingaddress text not null,
    trackingnumber text null
);

create table if not exists orderitem (
    orderitemid int generated by default as identity primary key,
    orderid int not null references orders (orderid),
    productid int not null references product (productid),
    quantity int not null,
    unitprice numeric(12, 2) not null
);

create table if not exists wishlist (
    wishlistid int generated by default as identity primary key,
    userid int not null references useraccount (userid),
    productid int not null references product (productid),
    addedat timestamptz not null default now(),
    constraint uq_wishlist_user_product unique (userid, productid)
);

create table if not exists review (
    reviewid int generated by default as identity primary key,
    productid int not null references product (productid),
    userid int not null references useraccount (userid),
    rating int not null check (rating between 1 and 5),
    comment text null,
    createdat timestamptz not null default now()
);

create table if not exists supportticket (
    ticketid int generated by default as identity primary key,
    userid int not null references useraccount (userid),
    subject text not null,
    message text not null,
    isresolved boolean not null default false,
    createdat timestamptz not null default now()
);

create table if not exists cart (
    cartitemid int generated by default as identity primary key,
    userid int not null references useraccount (userid),
    productid int not null references product (productid),
    quantity int not null default 1 check (quantity > 0),
    addedat timestamptz not null default now(),
    constraint uq_cart_user_product unique (userid, productid)
);

